package com.cycling.rssradar.core.domain.recommendation

/**
 * 冷启动时用户手选的兴趣领域（**纯本地、不调模型**）。
 *
 * 为什么需要它：兴趣画像是**只从真实行为推**的（打开 / 收藏 / 稍后读）。这保证了它可信，
 * 但也意味着"还没读过几篇"的新用户拿到的是空画像，推荐退化成纯按新鲜度排。
 * 让他先勾几个领域，等于在没有任何行为之前给画像一个**弱先验**。
 *
 * 三条边界都是刻意的：
 * 1. **权重弱于真实行为**：[RecommendationScoring.SEED_TERM_WEIGHT] 只相当于半篇被打开的文章
 *    ——读两篇就压过去了。勾选是"起步用的"，不是长期偏好设置，所以它不配拥有专用管理页。
 * 2. **词表固定、不给自由输入**：用户手写的词若与文章用词不同形（写「人工智能」而标题写「AI」），
 *    匹配不上却看着像生效了——那是最糟的一种"静默无效"。固定词表里每条都是常见词，
 *    至少能担保在真实标题里出现过。
 * 3. **可以随时取消**：界面上常驻而不是只在空画像时出现，否则勾过一次就再也撤不掉。
 */
object RecommendationSeeds {

    /**
     * 可勾选的领域。
     *
     * 取"宽而常见"这一档——它们要**为召回负责，不为精确负责**：
     * 精确度交给真实行为去修正，而一个冷启动词表如果收窄到"半导体设备"，它就什么也召不回。
     */
    val TOPICS: List<String> = listOf(
        "科技", "互联网", "人工智能", "编程", "商业", "财经",
        "设计", "职场", "科学", "历史", "文化", "影视",
        "游戏", "体育", "健康", "美食", "旅行",
    )

    /**
     * 勾选的领域是否在 [TOPICS] 里。
     *
     * 读档时要过这一关：词表是会改的（删掉一个领域、改一次写法），
     * 而 SharedPreferences 里存的是旧词。不剔除的话，用户会看到一条
     * 自己从没勾过、也取消不掉的选项（因为它不在候选里，点不到）。
     */
    fun sanitize(stored: Collection<String>): List<String> =
        stored.map { it.trim() }.filter { it in TOPICS }.distinct()
}
