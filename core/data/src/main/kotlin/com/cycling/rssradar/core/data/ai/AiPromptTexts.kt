字段：{"variants": [{"style": "SHORT"|"THREAD"|"BULLET", "text": 文案正文}]}
要求：
1. SHORT：一两句话说清这篇文章讲了什么、为什么值得看，80 字以内。
2. THREAD：3 到 5 句连贯展开，适合长平台，200 字以内。
