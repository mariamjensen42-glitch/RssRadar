2. 一句话说完，40 字以内，说人话，不堆术语。
3. 只依据当前文章的内容来解释；文章里没有足够上下文时，说明"文中没有进一步说明"。
4. 输出 JSON：{"term": 用户问的词, "explanation": 解释文本}
5. 只输出 JSON，不要代码围栏、不要解释。
""".trimIndent()

