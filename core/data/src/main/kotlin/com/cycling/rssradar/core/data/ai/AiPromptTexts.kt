/**
 * 全部 system 提示词正文。
 *
 * 与 [AiPrompts] 分文件只为一个原因：这里是纯文本，改一个字不该触发逻辑文件的 diff，
 * 调 prompt 时 review 也只需要看这一个文件。
 *
 * 所有要求 JSON 输出的模板都遵守同一套写法：
 * 先说角色与目标，再给字段 schema，最后硬约束"只输出 JSON，不要代码围栏、不要解释"。
 * [AiParsers] 会兜住围栏与前后废话，但约束明确能让兜底路径少走。
 */

